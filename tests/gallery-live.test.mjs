import assert from 'node:assert/strict';
import test from 'node:test';
import WebSocket from 'ws';
import { applyGalleryPatch } from '../src/gallery-patch.js';

const origin = process.env.STUDIO_TEST_ORIGIN;
test('ordinary gallery publications use deltas and a full resync preserves the archive', { skip: !origin, timeout: 45000 }, async t => {
  await new Promise((resolve, reject) => {
    const socket = new WebSocket(new URL('/api/studio-events', origin).href.replace(/^http/, 'ws'), { origin });
    let snapshot;
    let initialBytes;
    let preview;
    let patches = 0;
    let resyncVersion = null;
    let resynced = false;
    let complete = false;
    const samples = [];
    const timeout = setTimeout(() => { socket.terminate(); reject(new Error('No ordinary completion/resync observed; no work was generated by this test')); }, 40000);
    const fail = error => { clearTimeout(timeout); socket.terminate(); reject(error); };
    socket.on('error', fail);
    socket.on('open', () => socket.send(JSON.stringify({ type: 'subscribe', topics: ['gallery'], features: ['gallery-patch-v1', 'gallery-preview-v1'] })));
    socket.on('message', bytes => {
      try {
        const message = JSON.parse(bytes);
        if (message.topic === 'gallery-recent') {
          assert.equal(message.type, 'snapshot');
          assert.ok(message.data.jobs.length <= 36);
          preview = message.data;
          return;
        }
        if (message.topic !== 'gallery') return;
        assert.notEqual(message.type, 'unavailable');
        if (message.type === 'snapshot') {
          assert.ok(preview, 'recent image metadata arrives before the full archive');
          assert.ok(message.data.jobs.length >= preview.jobs.length);
          if (resyncVersion !== null) {
            assert.ok(message.version >= resyncVersion);
            if (message.version === snapshot.version) assert.deepEqual(message.data, snapshot.data, 'full resync matches reconstructed full archive');
            resynced = true;
          }
          snapshot = { ...message, available: true };
          initialBytes ??= bytes.length;
        } else if (message.type === 'patch') {
          assert.equal(message.baseVersion, snapshot.version);
          snapshot = applyGalleryPatch(snapshot, message);
          patches++;
          samples.push({ bytes: bytes.length, upserts: message.upserts.length, archived: snapshot.data.jobs.length, publicationAgeMs: Date.now() - Date.parse(message.observedAt) });
          if (patches === 1) {
            resyncVersion = snapshot.version;
            socket.send(JSON.stringify({ type: 'resync', topic: 'gallery' }));
          }
        }
        if (patches >= 3 && resynced) {
          assert.ok(samples.some(sample => sample.bytes < initialBytes / 10), 'ordinary updates avoid retransmitting the complete archive');
          clearTimeout(timeout); complete = true;
          socket.close(); t.diagnostic(JSON.stringify({ initialBytes, samples })); resolve();
        }
      } catch (error) { fail(error); }
    });
    socket.on('close', code => { if (!complete) fail(new Error('Unexpected socket close ' + code)); });
  });
});
